def build_optimize_prompt(
    resume_text: str,
    target_role: str = "",
    target_company: str = "",
    template_mode: str = "builtin",
    custom_template: str = "",
    jd_text: str = "",
) -> str:
    """构建第 1 轮优化 Prompt"""
    extra = ""
    if target_role:
        extra += f"\n- 目标岗位：{target_role}"
    if target_company:
        extra += f"\n- 目标公司：{target_company}"

    format_rules = _format_rules()
    template_section = _template_section(template_mode, custom_template)

    # JD 段落
    jd_section = ""
    if jd_text.strip():
        jd_section = f"""
## 📋 目标 JD（岗位描述）

{jd_text.strip()}

## JD 匹配分析要求（重要）

请将 JD 作为优化的重要参考依据：

1. **提取 JD 核心要求**：硬性要求（技能/经验/学历）和软性要求（沟通/协作/自驱等）
2. **在「问题分析」中标注 JD 差距**：每条分析除了常规维度，还要说明「JD 要求 X，简历中缺失/不足」
3. **在「优化版本」中填补 JD 缺口**：将 JD 中的关键词自然融入优化后的表述，优先覆盖 JD 硬性要求
4. **在「优化理由」中说明 JD 匹配**：解释优化后如何更好地匹配 JD 要求

"""

    return f"""你是一位资深 HR 兼简历优化专家，擅长用 STAR 法则润色技术类简历。

## 🚫 严禁造假（最高优先级，违反则输出无效）

以下规则优先级高于所有其他优化要求：

**数据规则**：
- ❌ 错误：原文"做了个网站" → 优化成"网站月活 5000+，转化率提升 30%"
- ✅ 正确：原文"做了个网站" → 优化成"独立完成网站搭建并上线，可公开访问"
- 原文没有的数字，用定性描述代替，**禁止估算任何具体数值**
- 原文有的数字，原样保留

**身份信息规则**：
- 项目起止时间、项目角色/职位：保留原文，不编造不修改
- 求职意向：根据用户填写的「目标岗位」来写；用户未填则保留原文
- 专业技能：以用户原文列出的范围为准，不新增技能

**标注规则**：
- 如果你认为某个地方强烈需要数据支撑，写成「[建议补充：具体什么数据]」，让用户自己填

请对以下简历内容进行专业优化。{extra}

## 简历原文
{resume_text}

{jd_section}{template_section}

## 输出要求
请严格按照以下四个板块输出，内容详尽、具体、可直接使用。
{format_rules}

### 📋 原句
逐条列出原文中**所有板块**的关键内容（方便对比），编号展示。必须覆盖：
- 求职意向/目标岗位
- 专业技能（含工具）
- 项目经历（每条 bullet 单独编号）
- 教育背景
- 自我评价（如有）
- 证书与语言（如有）
如果原文缺少某板块，标注「原文无此板块」即可，不要跳过。

### 🔍 问题分析
逐条指出每条内容的不足，覆盖：
- 是否缺少具体数据/量化指标
- 动词是否足够有力（"参与""负责"→"主导""设计""优化"）
- 是否体现个人贡献（而非团队模糊表述）
- STAR 结构是否完整（情境-任务-行动-结果）
- 技术关键词是否突出

### ✅ 优化版本
逐条给出优化后的完整句子：
- 使用强有力的动作动词开头（主导、设计、优化、重构、搭建…）
- **数据原则：原文有数据 → 保留并用；原文无数据 → 用定性描述，绝不编造数字**
- 如果确实需要建议一个数值供用户参考，必须加「[建议核实：原文无此数据]」标注
- 项目时间和项目角色保留原文，不做改动
- 突出技术关键词
- 符合 STAR 法则
- 每条控制在 1-2 句话

### 💡 优化理由
逐条解释优化逻辑：
- 用了什么技巧（量化、动词增强、结构重组…）
- 解决了原文的什么问题
- 预计在 HR/面试官眼中的效果提升"""


