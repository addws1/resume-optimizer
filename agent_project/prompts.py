from pathlib import Path


# ══════════════════════════════════════════════════════════════
# 模板加载
# ══════════════════════════════════════════════════════════════

def _load_template() -> str:
    """加载简历模板文件。文件不存在时静默返回空字符串。"""
    template_path = Path(__file__).parent / "resume_template.md"
    try:
        if template_path.exists():
            return template_path.read_text(encoding="utf-8")
    except Exception:
        pass
    return ""


def _template_section(template_mode: str = "builtin", custom_template: str = "") -> str:
    """
    构建模板参考段落。

    Args:
        template_mode: "builtin"（内置模板）/ "custom"（自定义模板）/ "none"（不用模板）
        custom_template: 自定义模板的文本内容（仅 mode="custom" 时使用）
    """
    # 不用模板
    if template_mode == "none":
        return """
## 无需参考模板

用户选择不使用模板。请**完全保留用户原有简历的章节结构和排版格式**，
只优化内容质量（措辞、量化、动词、STAR 法则），不要改变结构。

**🚫 严禁造假**：
- 原文没有的数据不要编造，用定性描述代替
- 项目时间和项目角色保留原文
- 求职意向保留原文
- 专业技能范围以原文为准，不新增
"""

    # 确定模板内容
    if template_mode == "custom" and custom_template.strip():
        template = custom_template.strip()
        source_label = "用户上传的自定义模板"
    else:
        template = _load_template()
        source_label = "内置模板（AI 产品实习生方向）"

    if not template.strip():
        return ""

    return f"""
## 参考模板（排版格式 + 语言风格标杆）

以下是一份{source_label}。请按以下规则使用模板：

**🔒 不可改（严格照模板的排版和格式）**：
- 大标题（章节名）不动：求职意向、专业技能、项目经历、教育背景、自我评价、证书与语言——这些章节标题原样保留
- 排版层次不变：标题层级（#、##、###）、分隔线（---）、联系方式一行的格式——照模板来
- 字体/样式风格：加粗、列表符号、段落间距——跟模板一致

**✏️ 可优化（内容可以改）**：
- 专业技能的具体描述可以改写得更精准，但**技能范围以用户原文为准**，不要无中生有添加用户没提的技能
- 项目经历的 bullet 内容可以优化措辞、补充逻辑链，但项目时间、项目角色/负责人这些信息必须保留原文，用户自己填
- 自我评价可以调整表述，但保持真实口吻

**🚫 严禁造假（最高优先级）**：
- **宁可保留原文的模糊表述，也绝不要编造具体数字**（用户数、百分比、增长率等）
- 如果原文没有数据，优化时用定性描述代替（如"显著提升""有效改善"），**不要**估算具体数值
- 如果确实需要给出参考数字让用户自己确认，必须加「[建议核实：原文无此数据]」后缀
- **项目时间（起止日期）**：保留用户原文，不要修改或编造
- **项目角色/负责人 title**：保留用户原文，不要修改或编造
- **求职意向**：根据用户填写的"目标岗位"来写，不要照抄模板
- 优化理由中如果提到"补充了量化数据"，必须说明该数据是原文就有还是估算的

**⚠️ 模板适用范围（关键）**：
模板本身是一份 AI 产品实习生的简历，**不代表用户也应聘 AI 产品岗位**：
- **用户简历中没有 AI / 大模型 / Agent 相关经历的，绝不要从模板里搬运 AI 技能分类**（如"AI产品能力""RAG""Prompt Engineering"等）
- 用户简历中的专业技能分类（如"机械设计""财务管理""教学能力"）是什么就用什么，模板只提供排版和语言风格参考
- **严禁把用户的非 AI 简历改写成 AI 简历**——求职意向和技能范围必须忠于原文
- 如果用户原文的某个技能板块内容较少，不要用模板内容填充——写成用户实际有的内容，或标注「建议补充」

**语言风格要求**：
- 动词前置（主导、设计、搭建、驱动、沉淀…），避免"参与""负责""进行"
- 每条 bullet 包含：做了什么 → 为什么这样做（业务痛点/产品问题）→ 用了什么方法 → 产生了什么价值

**深度要求**：
- 专业技能每项 1-2 句，以用户原文的技能分类为准
- 项目经历每个项目 4-6 条 bullet，每条 1-2 句，要有具体技术名词和业务结果
- 自我评价 3-4 句话，突出自学路径 + 复合能力 + 产品热情

=== 模板内容 ===
{template}
=== 模板结束 ===
"""


