# 共享格式规则（所有输出型 prompt 引用）
# ══════════════════════════════════════════════════════════════

def _format_rules() -> str:
    """返回强制格式约束文本，确保 LLM 输出可被解析器正确拆分"""
    return """## ⚠️ 强制格式要求（必须严格遵守，否则结果无法正常显示）

【硬性规则】
1. 四个板块一个都不能少，即使某个板块无内容也必须写出标题行
2. 每个板块标题必须独占一行，以 "### " 开头（三个英文井号 + 一个空格）
3. 必须使用以下精确的标题文字（含 emoji）：
   ### 📋 原句
   ### 🔍 问题分析
   ### ✅ 优化版本
   ### 💡 优化理由
4. 顺序必须严格为：原句 → 问题分析 → 优化版本 → 优化理由
5. 标题行后不能跟其他内容，标题独占一行
6. 不要使用其他标题级别（## 或 ####），不要省略 ### 前缀"""


