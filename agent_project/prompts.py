def build_review_prompt(round1_output: str, original_text: str, jd_text: str = "") -> str:
    """构建 Agent 自审 Prompt——检查第 1 轮输出并挑出具体缺陷"""
    jd_part = ""
    if jd_text.strip():
        jd_part = f"""

## 目标 JD（作为审核参照）
{jd_text.strip()}"""

    return f"""你是一位严格的简历质量审核专家。以下是 AI 对一份简历的优化结果。请逐条审查，挑出所有可以改进的地方。

## 简历原文
{original_text}
{jd_part}

## 优化结果
{round1_output}

## 审查要求
请逐条检查，只要存在以下任一问题就列出来：

1. **量化不足**：优化版本中有没有仍然缺少具体数据的地方？[建议核实] 的估算是否合理？
2. **动词偏弱**：有没有仍然使用"参与""负责""进行"等弱动词的地方？
3. **STAR 不完整**：有没有缺少"结果"或"行动"的条目？
4. **个人贡献模糊**：读起来像团队成果而非个人贡献的？
5. **技术关键词缺失**：应该突出但未突出的技术栈？
6. **表达冗长**：超过 2 句话、读起来拖沓的条目？
7. **遗漏原文亮点**：原文中有价值的信息在优化版中被丢掉的？
8. **编造数据**：优化版中是否出现了原文没有的具体数字且未标注 [建议核实]？是否改了项目时间或项目角色？
9. **JD 关键词缺失**：JD 中的关键技能或经验要求，优化版中是否未覆盖或未体现？

## 输出格式
请按以下格式输出：

### 🔍 自审发现
逐条列出缺陷，每条说明：
- 哪个条目有问题
- 具体什么问题
- 建议怎么改（一句话方向即可）

如果没有发现任何问题，请输出"✅ 审查通过，无需修改。" """


