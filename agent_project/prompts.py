# Agent 自评总结
# ══════════════════════════════════════════════════════════════

def build_self_assessment_prompt(
    original_text: str,
    final_output: str,
    review_findings: str,
    final_resume: str = "",
    jd_text: str = "",
) -> str:
    """构建 Agent 自评总结——多维度评分 + 定性总结"""
    jd_section = ""
    jd_dim_line = ""
    if jd_text.strip():
        jd_section = f"""
## 目标 JD
{jd_text.strip()[:1500]}"""
        jd_dim_line = "\nJD匹配度: <分数>"

    resume_to_score = final_resume or final_output

    return f"""你是一位诚实的简历优化专家。你刚完成了一轮优化+自审+改进。请先打分再给总结。

## 优化后简历（评分依据）
{resume_to_score[:2500]}

## 优化前后对比
- 原文：{original_text[:500]}
- 优化后：{final_output[:800]}

## 自审发现的问题
{review_findings[:500]}
{jd_section}

## ⚠️ 强制输出格式

### 📊 简历评分

请对以下维度逐一给出 0-100 的分数：

STAR完整度: <分数>（bullet 是否包含情境-任务-行动-结果完整链路）
量化率: <分数>（多少 bullet 有数据或可度量成果）
动词力度: <分数>（强动词如主导/设计/搭建 vs 弱动词如参与/负责）
技术关键词密度: <分数>（技术栈关键词是否充分且自然）
个人贡献清晰度: <分数>（能否看出你的个人贡献而非团队模糊描述）
表达简洁度: <分数>（是否精炼，每条 1-2 句）{jd_dim_line}
综合评分: <分数>（加权综合，STAR 完整度和量化率权重更高）

评分约束：基于实际水平打分，优劣势拉开至少 15 分差距，不要全打相近分。

在维度评分之后，请根据原始简历和优化后简历的差距，输出：

原始综合分: <分数>
优化综合分: <分数>
△提升: <差值>

（原始综合分根据原始简历的STAR完整度、量化率、动词力度等综合评估；优化综合分即上面的综合评分；△提升 = 优化综合分 - 原始综合分）

### 💬 优化总结
用一段话（100-150字）告诉用户：
1. 本次优化的重点是什么
2. 改进了哪些具体方面
3. 还有什么地方可以进一步确认（如建议核实的数据）

语气真诚、专业，不要过度承诺。"""


